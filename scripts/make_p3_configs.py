"""Generate the Phase-3 configs (configs/p3_*.yaml) on top of a chosen base preprocessing, so that
every idea is "one change" relative to the base (docs/decisions.md).

usage: python scripts/make_p3_configs.py --base hybrid|peaknorm|zscore
"""
import argparse
import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
FCN4 = ["fcn_w0", "fcn_w1", "fcn_w2", "fcn_w3"]
BASES = {
    "peaknorm": dict(opts={"target": "peaknorm"}, tag="pn", exp="p2_norm", suffix="peaknorm"),
    "hybrid": dict(opts={"target": "peaknorm", "pn_bands": [0], "standardize": True}, tag="hyb", exp="p2_hybrid", suffix="hyb"),
    "zscore": dict(opts={"standardize": True}, tag="z", exp="p2_zscore", suffix="z"),
}


def spec(name, configs, base, fcn=False, **kw):
    s = {"name": name, "type": "dl", "configs": configs}
    s.update(copy.deepcopy(base["opts"]))
    s.update(kw)
    if fcn and s.get("target") in ("peaknorm", "pn_resid", "resid_prior"):
        s.setdefault("overrides", {})["anchor"] = False
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="peaknorm", choices=list(BASES), help="base for GRU and modern nets")
    ap.add_argument("--base-fcn", default=None, choices=list(BASES))
    a = ap.parse_args()
    B = BASES[a.base]
    BF = BASES[a.base_fcn or a.base]
    t, tf = B["tag"], BF["tag"]
    G = lambda n, **kw: spec(f"GRU-{t}-{n}", ["gru"], B, **kw)              # noqa: E731
    F = lambda n, **kw: spec(f"FCN-{tf}-{n}", FCN4, BF, fcn=True, **kw)     # noqa: E731
    gru_band = [{"kind": "gru", "hidden_dim": 172, "num_layers": 2, "dropout": 0.1518, "lr": 5.8e-4, "batch_size": 8,
                 "bands": [b]} for b in range(4)]
    rt = lambda base: "pn_resid" if base["opts"].get("target") == "peaknorm" else "resid_prior"  # noqa: E731
    cfgs = {
        "p3_arch": [spec(n, [{"kind": k, "lr": 1e-3, "batch_size": 8, "dropout": 0.1}], B)
                    for n, k in [("PatchTST", "patchtst"), ("TSMixer", "tsmixer"), ("N-BEATS", "nbeats"),
                                 ("ModernTCN", "moderntcn")]],
        "p3_resid": [{"name": "Prior-only", "type": "baseline", "baseline": "powerlaw_rt"},
                     G("resid", target=rt(B)), F("resid", target=rt(BF))],
        "p3_extreme": [G("wtop3", weight_top=3), G("noise", augment={"noise": 0.01}),
                       F("noise", augment={"noise": 0.01})],
        "p3_type": [G("experts", experts="rise_min_10pct"), G("typefeat", extra=["rise_min_10pct"])],
        "p3_joint": [spec(f"GRU-{t}-perband", gru_band, B),
                     dict(spec(f"FCN-{tf}-joint", ["fcn_w0"], BF, fcn=True),
                          overrides={"bands": [0, 1, 2, 3], "anchor": BF["opts"].get("target") != "peaknorm"})],
        "p3_features": [G("feat", extra=["rise_min_10pct", "rise_slope_10", "x_ratio_60", "hgs_lon", "has_lon", "is_x"],
                          perm_importance=True),
                        F("feat", extra=["rise_min_10pct", "rise_slope_10", "x_ratio_60", "hgs_lon", "has_lon", "is_x"],
                          perm_importance=True)],
        "p3_early": [G(f"lead{L}", input_offset=L, in_window=60 - L) for L in (10, 20, 30)]
                    + [F(f"lead{L}", input_offset=L, in_window=60 - L) for L in (10, 20, 30)],
        "p3_ensemble": [spec(f"GRU-{B['suffix']}", ["gru"], B), spec(f"FCN-{BF['suffix']}", FCN4, BF, fcn=True)],
    }
    for exp, specs in cfgs.items():
        doc = {"exp_id": exp, "seeds": [0, 1, 2, 3, 4] if exp == "p3_ensemble" else [0, 1, 2],
               "base": a.base, "base_fcn": a.base_fcn or a.base, "specs": specs}
        with open(ROOT / "configs" / f"{exp}.yaml", "w") as fh:
            fh.write(f"# Phase 3 — generated by scripts/make_p3_configs.py --base {a.base} --base-fcn {a.base_fcn or a.base}\n")
            yaml.safe_dump(doc, fh, sort_keys=False, default_flow_style=None, width=200)
    print("base", a.base, "->", list(cfgs))


if __name__ == "__main__":
    main()
